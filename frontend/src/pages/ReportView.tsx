import { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import ReportCharts from '../components/ReportCharts';
import { api, type Report } from '../lib/api';

const n = (v: number) => String(Number(v.toFixed(2)));

export default function ReportView() {
  const { id = '' } = useParams();
  const [report, setReport] = useState<Report | null>(null);
  const [dsName, setDsName] = useState<string>('');
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    api.getReport(id).then(async r => {
      setReport(r);
      const all = await api.listDatasets().catch(() => []);
      setDsName(all.find(d => d._id === r.datasetId)?.name ?? '');
    }).catch(e => setError((e as Error).message));
  }, [id]);

  if (error) return <div role="alert" className="space-y-3"><p className="rounded-md border border-red-300 bg-red-50 px-3 py-2 text-sm text-red-800">{error}</p><Link to="/reports" className="btn-ghost">Back to reports</Link></div>;
  if (!report) return <p className="text-sm">Loading report…</p>;
  const { summary, filters } = report;

  return (
    <article className="space-y-8">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <Link to="/reports" className="text-sm text-forest hover:underline print:hidden">← Reports</Link>
          <h1 className="font-serif text-3xl">{report.title}</h1>
          <p className="text-sm text-charcoal/70">{dsName && `Dataset: ${dsName} · `}Created {new Date(report.createdAt).toLocaleString()}</p>
        </div>
        <button className="btn print:hidden" onClick={() => window.print()}>Print / Save as PDF</button>
      </div>

      <section>
        <h2 className="mb-2 font-serif text-xl">Scope</h2>
        <p className="text-sm">{filters.rowsIncluded.toLocaleString()} rows included.{' '}
          {!filters.search && filters.filters.length === 0 ? 'No search or filters applied.' : ''}</p>
        <ul className="mt-1 list-disc pl-5 text-sm">
          {filters.search && <li>Search: “{filters.search}”</li>}
          {filters.filters.map((f, i) => <li key={i}>{f.column} {f.op} {f.value}</li>)}</ul>
      </section>

      <section>
        <h2 className="mb-2 font-serif text-xl">Observations</h2>
        <ul className="list-disc space-y-1 pl-5 text-sm">{report.observations.map((o, i) => <li key={i}>{o}</li>)}</ul>
        <p className="mt-2 text-xs text-charcoal/60">Generated by fixed rules from the calculated statistics below.</p>
      </section>

      <ReportCharts columns={summary.columns} />

      <section>
        <h2 className="mb-2 font-serif text-xl">Column statistics</h2>
        <div className="overflow-x-auto"><table className="w-full text-left text-sm">
          <thead><tr className="border-b border-line">{['Column', 'Type', 'Missing', 'Distinct', 'Details'].map(h => <th key={h} className="px-2 py-1.5 font-medium">{h}</th>)}</tr></thead>
          <tbody>{summary.columns.map(c => (
            <tr key={c.name} className="break-inside-avoid border-b border-line/60 align-top">
              <td className="px-2 py-1.5 font-medium">{c.name}</td><td className="px-2 py-1.5">{c.type}</td>
              <td className="px-2 py-1.5 tabular-nums">{c.missing} ({c.missingPct.toFixed(1)}%)</td><td className="px-2 py-1.5 tabular-nums">{c.distinct}</td>
              <td className="px-2 py-1.5">
                {c.numeric && `min ${n(c.numeric.min)}, mean ${n(c.numeric.mean)}, median ${n(c.numeric.median)}, max ${n(c.numeric.max)}`}
                {c.dates && `${c.dates.min} to ${c.dates.max}`}
                {c.categories && c.categories.slice(0, 5).map(x => `${x.value} (${x.count})`).join(', ')}</td>
            </tr>))}</tbody></table></div>
      </section>
    </article>
  );
}
